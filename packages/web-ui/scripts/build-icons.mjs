// Copies the Material Symbols (Rounded, weight 400) the site uses into src/components/icon-paths.ts,
// so the site ships a few inline SVG paths instead of an icon font. Apache-2.0, Google.
//
//   npm pack @material-symbols/svg-400 && tar xzf material-symbols-svg-400-*.tgz
//   node scripts/build-icons.mjs <path to the unpacked package/rounded>
//
// Add a name to ICONS and run it again to use a new icon.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ICONS = [
  'analytics', 'arrow_forward', 'bakery_dining', 'call', 'campaign', 'check_circle', 'close', 'emoji_food_beverage',
  'explore', 'favorite', 'groups', 'handshake', 'local_cafe', 'location_on', 'lock', 'loyalty',
  'mail', 'menu', 'mobile', 'fiber_new', 'notifications', 'person_add', 'print', 'qr_code_2', 'qr_code_scanner',
  'receipt_long', 'redeem', 'restaurant', 'schedule', 'shield', 'stars', 'storefront',
  'support_agent', 'timer', 'trending_up', 'verified', 'workspace_premium',
  // The app's navigation set (brand board): Home, Rewards, Vouchers, Wallet, History, Account
  'home', 'layers', 'confirmation_number', 'account_balance_wallet', 'history', 'person',
  // Portals (merchant, admin): data tables, forms and actions
  'search', 'filter_list', 'download', 'upload', 'edit', 'add', 'delete', 'block', 'undo', 'chevron_left', 'chevron_right',
  'keyboard_arrow_down', 'more_vert', 'logout', 'settings', 'description', 'attach_file', 'image', 'badge', 'key', 'fingerprint',
  'payments', 'receipt', 'dashboard', 'store', 'apartment', 'calendar_month', 'pending', 'task_alt', 'cancel', 'flag',
  'warning', 'gpp_maybe', 'admin_panel_settings', 'manage_accounts', 'query_stats', 'bar_chart', 'featured_seasonal_and_gifts', 'sell',
  'point_of_sale', 'contact_support', 'open_in_new', 'content_copy', 'refresh', 'send', 'campaign', 'notifications_active',
  'group_add', 'person_off', 'how_to_reg', 'pause_circle', 'play_circle', 'public', 'tune', 'help',
  // Status
  'error', 'info',
  // Forms
  'visibility', 'visibility_off',
];

const source = process.argv[2];
if (!source) {
  console.error('usage: node scripts/build-icons.mjs <material-symbols svg-400 rounded folder>');
  process.exit(2);
}
const entries = [...new Set(ICONS)].map((name) => {
  const svg = readFileSync(join(source, `${name}.svg`), 'utf8');
  const paths = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length !== 1) throw new Error(`${name}: expected one path, found ${paths.length}`);
  return `  ${name}: '${paths[0]}',`;
});
const out = `// Generated by scripts/build-icons.mjs from @material-symbols/svg-400 (rounded), Apache-2.0. Do not edit.
// viewBox "0 -960 960 960".
export const ICON_PATHS = {
${entries.join('\n')}
} as const;

export type IconName = keyof typeof ICON_PATHS;
`;
writeFileSync(new URL('../src/components/icon-paths.ts', import.meta.url), out);
console.log(`wrote ${ICONS.length} icons`);
