"""Regenerates packages/brand/src/geometry.ts from the brand board and the fonts.

  python3 -m venv .venv && .venv/bin/pip install pillow fonttools uharfbuzz
  .venv/bin/python tools/build_geometry.py "<board.png>" <Montserrat[wght].ttf> <Inter-Italic[opsz,wght].ttf>

The result is committed, so this only needs to run when the artwork or the fonts change.
"""
import json, os, subprocess, sys, tempfile
sys.path.insert(0, os.path.dirname(__file__))
from text_paths import outline

board, montserrat, inter_italic = sys.argv[1:4]
here = os.path.dirname(os.path.abspath(__file__))
work = tempfile.mkdtemp()
subprocess.run([sys.executable, os.path.join(here, 'trace_mark.py'), board, work], check=True)
traced = json.load(open(os.path.join(work, 'pieces.json')))

pieces = []
for name in ['purple', 'blue', 'yellow', 'orange']:   # bottom to top
    p = traced['pieces'][name]
    g = p['grad']
    pieces.append({'name': name, 'd': p['d'], 'gradient': {'x1': g['x1'], 'y1': g['y1'], 'x2': g['x2'], 'y2': g['y2'], 'stops': g['stops']}})

wm_d, wm_w = outline(montserrat, 'UGNAYA', 800, 1000)
tm_d, tm_w = outline(montserrat, 'TM', 700, 1000)
tg_d, tg_w = outline(inter_italic, 'One Wallet. More Places. More Rewards.', 500, 1000)

def ts(o): return json.dumps(o, separators=(',', ':'))
out = f"""// Generated by tools/build_geometry.py from the brand board and the fonts. Do not edit by hand.
// The mark is traced from "UGNAYA Brand Identity Showcase.png" as four ribbon pieces (bottom to top),
// each filled with a gradient fitted to the board's colours. Text is outlined (Montserrat ExtraBold,
// Montserrat Bold for TM, Inter Medium Italic for the tagline), set at 1000 units per em.

export type GradientStop = readonly [offset: number, color: string];
export type MarkPiece = {{
  name: 'purple' | 'blue' | 'yellow' | 'orange';
  d: string;
  gradient: {{ x1: number; y1: number; x2: number; y2: number; stops: readonly GradientStop[] }};
}};

export const MARK = {{ width: {traced['viewBox'][2]}, height: {traced['viewBox'][3]}, pieces: {ts(pieces)} as readonly MarkPiece[] }} as const;

/** "UGNAYA" in Montserrat ExtraBold, baseline at y=0, cap height 700. */
export const WORDMARK = {{ d: {ts(wm_d)}, width: {wm_w:.1f}, capHeight: 700 }} as const;
/** The trademark sign, Montserrat Bold "TM". */
export const TRADEMARK = {{ d: {ts(tm_d)}, width: {tm_w:.1f}, capHeight: 700 }} as const;
/** "One Wallet. More Places. More Rewards." in Inter Medium Italic. */
export const TAGLINE = {{ d: {ts(tg_d)}, width: {tg_w:.1f} }} as const;
"""
open(os.path.join(here, '..', 'src', 'geometry.ts'), 'w').write(out)
print('wrote geometry.ts', len(out), 'bytes')
