#!/usr/bin/env bash
# Generates packages/db/src/database.types.ts from the migrations, without Docker or a linked
# project: a throwaway Postgres with the Supabase stand-ins and every migration, read by the
# Supabase CLI. Usage: npm run db:types:local
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
HERE="$ROOT/scripts/sql-tests"
WORK="$(mktemp -d)"
PORT="${TYPES_PORT:-54340}"
OUT="$ROOT/packages/db/src/database.types.ts"
export PGHOST="$WORK" PGPORT="$PORT" PGUSER=postgres

psql_on() { env PGOPTIONS=-cclient_min_messages=warning psql -X -q -d "$1" -v ON_ERROR_STOP=1 "${@:2}"; }
cleanup() {
  pg_ctl -D "${WORK:?}/data" -m immediate stop >/dev/null 2>&1 || true
  rm -rf "${WORK:?}"
}
trap cleanup EXIT

initdb -D "$WORK/data" -U postgres --auth=trust >/dev/null
pg_ctl -D "$WORK/data" -o "-p $PORT -k $WORK -c listen_addresses=127.0.0.1" -l "$WORK/log" -w start >/dev/null
psql_on postgres -f "$HERE/roles.sql"
createdb types
psql_on types -f "$HERE/stand-ins.sql"
for migration in "$ROOT"/supabase/migrations/*.sql; do psql_on types -f "$migration"; done

TMP="$WORK/types.ts"
(cd "$ROOT" && npx --no-install supabase gen types typescript --schema public \
  --remote="postgresql://postgres@127.0.0.1:$PORT/types?sslmode=disable") > "$TMP"
grep -q 'export type Database' "$TMP" || { echo "FAIL: no types generated"; cat "$TMP"; exit 1; }
{ echo '// Generated by `npm run db:types:local` from supabase/migrations. Do not edit.'; cat "$TMP"; } > "$OUT"
echo "wrote $OUT"
